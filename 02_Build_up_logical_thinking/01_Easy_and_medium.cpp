/*These patterns teach the basic nested loop structure — the outer loop controls rows, and the inner loop
  controls the columns/characters printed in each row.*/

/*Easy Level Patterns (usually cover):

1.Solid rectangle/square (fixed rows × fixed columns)
2.Right-angled triangle (rows increase, and columns increase with the row number)
3.Inverted triangle (rows decrease)
4.Number patterns (1,2,3... or 1,1,1... type)*/

/*Medium Level Patterns (usually cover):

1.Pyramid (combination of spaces + stars)
2.Diamond pattern (upper triangle + mirrored lower triangle)
3.Number pyramid, palindrome pattern (1,12,123,12321 type)
4.Character patterns (A,B,C or ABC,AB,A type)

Medium patterns require handling two things at once:

1.Spaces — which decrease or increase with each row (follows an n - i type formula)
2. Actual characters/stars — which follow a 2*i - 1 type formula (odd number sequence)*/