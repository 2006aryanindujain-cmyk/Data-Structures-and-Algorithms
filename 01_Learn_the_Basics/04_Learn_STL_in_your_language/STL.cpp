// STL is one of the unique abilities of C++ which makes it stand out from every other programming language. STL stands for
// standard template library which contains a lot of pre-defined templates in terms of containers and classes which makes it
// very easy for developers or programmers to implement different data structures easily without having to write complete code
// and worry about space-time complexities.

// STL is a collection of generic containers, algorithms, iterators, and function objects provided by C++ for
// efficient data manipulation.

// Main components of STL:
// 1. Containers  -> store data
// 2. Algorithms  -> perform operations
// 3. Iterators   -> traverse/access elements

// Common Containers:
// vector, stack, queue, set, map, unordered_map, priority_queue

// Common Algorithms:
// sort(), reverse(), find(), count(), binary_search()
